package com.gauthig.flexandroid.data

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import android.util.Log
import java.security.GeneralSecurityException
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * AES-256-GCM encryption under a key held in the Android keystore.
 *
 * This exists instead of `androidx.security:security-crypto` because that library
 * is deprecated as of 1.1.0 with no drop-in successor. The job here is small and
 * well-defined — encrypt one short string at rest — so it is done directly against
 * the platform primitive rather than through an abandoned wrapper.
 *
 * The key never leaves the keystore: it is generated there, used by handle, and is
 * unextractable even by this app. On devices with a hardware-backed keystore that
 * means the secret cannot be recovered by copying the app's data directory.
 *
 * GCM is used with a random 12-byte IV per encryption, prepended to the
 * ciphertext. Reusing an IV with GCM is catastrophic, so it is generated by the
 * cipher rather than by us.
 */
class KeystoreCipher(private val alias: String) {

    /**
     * Encrypts [plaintext], returning Base64 of `iv || ciphertext || tag`.
     *
     * Returns `null` if the keystore is unavailable, which some devices exhibit
     * after a lock-screen change. Callers treat that as "cannot persist" rather
     * than as a fatal error.
     */
    fun encrypt(plaintext: String): String? = try {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, loadOrCreateKey())
        val iv = cipher.iv
        val body = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
        Base64.encodeToString(iv + body, Base64.NO_WRAP)
    } catch (e: GeneralSecurityException) {
        Log.w(TAG, "encryption unavailable", e)
        null
    }

    /**
     * Decrypts a value produced by [encrypt].
     *
     * Returns `null` when the value is corrupt or when the key is gone — which
     * happens legitimately: adding or removing a device lock can invalidate
     * keystore entries. The caller's correct response is to ask the operator to
     * sign in again, not to crash.
     */
    fun decrypt(encoded: String): String? {
        return try {
            val raw = Base64.decode(encoded, Base64.NO_WRAP)
            // Anything this short cannot carry an IV plus a GCM tag.
            if (raw.size <= IV_BYTES) return null
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(
                Cipher.DECRYPT_MODE,
                loadOrCreateKey(),
                GCMParameterSpec(TAG_BITS, raw, 0, IV_BYTES),
            )
            String(cipher.doFinal(raw, IV_BYTES, raw.size - IV_BYTES), Charsets.UTF_8)
        } catch (e: GeneralSecurityException) {
            Log.w(TAG, "stored secret could not be decrypted; treating it as absent", e)
            null
        } catch (e: IllegalArgumentException) {
            Log.w(TAG, "stored secret was not valid Base64", e)
            null
        }
    }

    /** Removes the key, making every value encrypted under it unrecoverable. */
    fun deleteKey() {
        try {
            keyStore().deleteEntry(alias)
        } catch (e: GeneralSecurityException) {
            Log.w(TAG, "could not delete key", e)
        }
    }

    @Throws(GeneralSecurityException::class)
    private fun loadOrCreateKey(): SecretKey {
        val store = keyStore()
        (store.getEntry(alias, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, PROVIDER)
        generator.init(
            KeyGenParameterSpec.Builder(
                alias,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(KEY_BITS)
                // Not requiring user authentication is deliberate: the app has to
                // be able to reconnect on launch without a biometric prompt, and
                // the threat this protects against is offline data extraction,
                // not someone holding the unlocked phone.
                .setUserAuthenticationRequired(false)
                .build(),
        )
        return generator.generateKey()
    }

    @Throws(GeneralSecurityException::class)
    private fun keyStore(): KeyStore =
        KeyStore.getInstance(PROVIDER).apply { load(null) }

    private companion object {
        const val TAG = "KeystoreCipher"
        const val PROVIDER = "AndroidKeyStore"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val KEY_BITS = 256
        const val IV_BYTES = 12
        const val TAG_BITS = 128
    }
}
